-- Courier app schema -- fresh-install structure for all 7 tables.
-- Run by install/index.php (step: Database). Safe to re-run: every
-- statement is CREATE TABLE IF NOT EXISTS.
-- Standardized on utf8mb4 throughout for new installs (the columns that
-- pre-date this installer were latin1 in older deployments -- that no
-- longer matters for a fresh database).

