CREATE TABLE IF NOT EXISTS `mail_settings` (
  `id` tinyint(3) unsigned NOT NULL DEFAULT 1,
  `smtp_host` varchar(191) NOT NULL DEFAULT '',
  `smtp_port` smallint(5) unsigned NOT NULL DEFAULT 587,
  `smtp_encryption` varchar(10) NOT NULL DEFAULT 'tls',
  `smtp_username` varchar(191) NOT NULL DEFAULT '',
  `smtp_password_enc` text DEFAULT NULL,
  `smtp_from_email` varchar(191) NOT NULL DEFAULT '',
  `smtp_from_name` varchar(191) NOT NULL DEFAULT '',
  `smtp_reply_to` varchar(191) NOT NULL DEFAULT '',
  `bcc_enabled` tinyint(1) NOT NULL DEFAULT 0,
  `bcc_email` varchar(191) NOT NULL DEFAULT '',
  `notify_on_create` tinyint(1) NOT NULL DEFAULT 1,
  `notify_on_status_update` tinyint(1) NOT NULL DEFAULT 1,
  `updated_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS `email_templates` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `template_key` varchar(64) NOT NULL,
  `name` varchar(191) NOT NULL,
  `description` varchar(255) NOT NULL DEFAULT '',
  `subject` varchar(255) NOT NULL,
  `html_body` mediumtext NOT NULL,
  `text_body` mediumtext NOT NULL,
  `updated_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `template_key` (`template_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS `email_log` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `template_key` varchar(64) NOT NULL DEFAULT '',
  `recipient_email` varchar(191) NOT NULL,
  `recipient_name` varchar(191) NOT NULL DEFAULT '',
  `subject` varchar(255) NOT NULL DEFAULT '',
  `html_body` mediumtext NOT NULL,
  `text_body` mediumtext NOT NULL,
  `status` enum('sent','failed') NOT NULL,
  `error_message` varchar(500) NOT NULL DEFAULT '',
  `tracking_number` varchar(64) NOT NULL DEFAULT '',
  `created_at` datetime NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`id`),
  KEY `idx_created_at` (`created_at`),
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS `login_attempts` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `identifier` varchar(191) NOT NULL,
  `attempts` int(11) NOT NULL DEFAULT 1,
  `first_attempt_at` datetime NOT NULL,
  `locked_until` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_identifier` (`identifier`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
